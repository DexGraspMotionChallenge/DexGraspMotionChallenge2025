STAGES = (
    ("approach", 0, 30),
    ("pregrasp", 30, 41),
    ("closure", 41, 55),
    ("lift", 55, 69),
)
ACTION_GROUPS = (
    ("all", 0, 28),
    ("wrist_position", 0, 3),
    ("wrist_orientation", 3, 6),
    ("fingers", 6, 28),
)


def process_observation(observation, pro_dim, torch):
    """Apply the same feature mask used by the official BC evaluator."""
    fingertip_velocity = torch.arange(
        84, 149, device=observation.device).reshape(5, 13)[:, -6:].reshape(-1)
    removed = [
        torch.arange(56, 84, device=observation.device),
        torch.arange(149, 179, device=observation.device),
        fingertip_velocity,
    ]
    if pro_dim in (100, 128):
        removed.append(torch.arange(216, 222, device=observation.device))
    if pro_dim == 100:
        removed.append(torch.arange(28, 56, device=observation.device))
    if pro_dim not in (100, 128, 134):
        raise ValueError("Unsupported proprioception dimension: {}".format(pro_dim))
    mask = torch.ones(2582, dtype=torch.bool, device=observation.device)
    mask[torch.cat(removed)] = False
    return observation[..., mask]


