"""Diagnose teacher-forced BC error and closed-loop error accumulation.

This entry point is intentionally separate from the official challenge code.
It uses the frozen trajectory selection, first replays expert actions in the
current simulator, and then compares BC predictions on expert observations
and on observations generated by the policy itself.
"""

